  MG.t = function (key, vars) {
    let s = I.raw(key);
    if (s === undefined) return key;
    if (typeof s === 'string' && vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  };

